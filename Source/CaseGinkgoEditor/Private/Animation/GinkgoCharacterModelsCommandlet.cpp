UGinkgoCharacterModelsCommandlet::UGinkgoCharacterModelsCommandlet()
{
	IsClient = false;
	IsServer = false;
	IsEditor = true;
	LogToConsole = true;
}

int32 UGinkgoCharacterModelsCommandlet::Main(const FString& Params)
{
	auto* Mesh = LoadObject<USkeletalMesh>(nullptr, TEXT("/Game/Characters/UEFN_Mannequin/Meshes/SKM_UEFN_Mannequin"));
	auto* Source = Mesh ? MakeRig(TEXT("Ginkgo"), *Mesh, false) : nullptr;
	if (!Source) return 1;
	auto* Player = MakeModel(TEXT("Survival"), TEXT("/Game/Survival_Character/Meshes/SK_Survival_Character"), *Source, { TEXT("Backpack1") });
	auto* Man = MakeModel(TEXT("Man"), TEXT("/Game/Man/Mesh/Full/SK_Man_Full_03"), *Source);
	auto* Mercer = MakeModel(TEXT("GraveMercer"), TEXT("/Game/Grave_Mercer/Skeletal_Mesh/SK_Grave_Mercer"), *Source);
	auto* Quantum = MakeModel(TEXT("Quantum"), TEXT("/Game/QuantumCharacter/Mesh/SKM_QuantumCharacter"), *Source);
	using EPart = EGinkgoBodyPart;
	const bool bOK = Player && MakeEnemy(TEXT("Unarmored"), Man, {}, 0.f)
		&& MakeEnemy(TEXT("Light"), Quantum, { EPart::UpperChest }, 100.f)
		&& MakeEnemy(TEXT("Heavy"), Mercer, { EPart::Head, EPart::UpperChest, EPart::Abdomen, EPart::UpperLimbs, EPart::Legs, EPart::Feet }, 500.f);
	if (!bOK)
	{
		UE_LOG(LogGinkgoCharacterModels, Error, TEXT("角色外观或敌人类型生成失败。"));
		return 1;
	}
	// 导入的重甲材质实例在 5.8 需要单独记录蒙皮与布料用途，否则打包与 PIE 都会显示默认灰材质。
	auto* Cloth = LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/Grave_Mercer/Materials/MI_Grave_Mercer"));
	if (!Cloth || !Cloth->CheckMaterialUsage(MATUSAGE_SkeletalMesh) || !Cloth->CheckMaterialUsage(MATUSAGE_Clothing)) return 1;
	return !Cloth->GetPackage()->IsDirty() || SaveModelAsset(*Cloth) ? 0 : 1;
}
